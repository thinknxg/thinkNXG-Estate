def _process_installments(lease, spec):
	from thinknxg_estate.core.api import record_partial_payment
	today = getdate(nowdate())
	rows = frappe.get_all("Rent Installment", filters={"parent": lease.rent_schedule}, fields=["name"],
	                      order_by="installment_no asc")
	bank_idx = zlib.crc32(spec["key"].encode()) % 5
	future_cheques = 0
	for idx, rr in enumerate(rows, 1):
		row = frappe.get_doc("Rent Installment", rr.name)
		due = getdate(row.due_date)
		code = spec.get("over", {}).get(idx)
		if not code:
			if due <= today:
				code = "C" if spec["freq"] == "Monthly" else "P"
			elif due <= add_days(today, 7):
				code = "J"
			elif future_cheques < 2 and spec["freq"] != "Monthly":
				code = "R"
				future_cheques += 1
			else:
				code = "_"
		if spec.get("state") == "Terminated" and due > getdate(T(spec.get("terminate", 0))):
			code = "_"
		try:
			_apply_code(lease, row, due, code, spec, bank_idx + idx, record_partial_payment)
		except Exception as e:
			warn(f"{lease.name} installment {idx} ({code})", e)
			import traceback
			traceback.print_exc()
			frappe.db.rollback()
			raise


def _apply_code(lease, row, due, code, spec, bank_idx, record_partial_payment):
	if code == "_":
		return
	if code == "R":
		_make_pdc(lease, row, due, code, bank_idx)
		return
	si = _invoice(lease, row, due)
	pay_date = min(getdate(due), getdate(nowdate()))
	if code in ("O", "I"):
		return
	if code == "J":
		_make_pdc(lease, row, due, code, bank_idx)
		return
	if code == "C":
		record_partial_payment(row.name, flt(row.amount), "Cash", str(pay_date), "Rent received in cash at the office")
		return
	if code == "H":
		part = flt(row.amount) * 0.4
		record_partial_payment(row.name, part, "Cash", str(add_days(pay_date, 3)), "Part payment received in cash")
		return
	pdc = _make_pdc(lease, row, due, code, bank_idx)
	if code == "B":
		pe = pdc.payment_entry
		pdc.mark_deposited()
		pdc.db_set("deposit_date", add_days(due, 1))
		pdc.reload()
		pdc.mark_bounced("Insufficient funds in the drawer's account")
		if pe and frappe.db.get_value("Payment Entry", pe, "docstatus") == 0:
			frappe.db.set_value("Post Dated Cheque", pdc.name, "payment_entry", None)
			frappe.delete_doc("Payment Entry", pe, force=1, ignore_permissions=True)
		return
	# P: deposited and cleared on historic dates
	pe_name = pdc.payment_entry
	pe = frappe.get_doc("Payment Entry", pe_name)
	pe.posting_date = due
	pe.reference_date = due
	pe.submit()
	tag("Payment Entry", pe.name)
	pdc.reload()
	pdc.mark_deposited()
	pdc.db_set("deposit_date", add_days(due, 1))
	pdc.reload()
	pdc.mark_cleared()
	pdc.db_set("clearance_date", add_days(due, 2))
	frappe.db.set_value("Post Dated Cheque", pdc.name, "payment_entry", pe_name)
	frappe.db.set_value("Rent Installment", row.name, {"paid_amount": row.amount, "outstanding_amount": 0,
	                                                    "status": "Paid"})
	_record_payment_row(row, row.amount, add_days(due, 2), "Cheque", pe_name, f"Cheque {pdc.cheque_no} cleared")


