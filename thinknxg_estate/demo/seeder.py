def _finalise_state(lease, spec, state):
	unit = lease.unit
	if state == "Expiring":
		frappe.db.set_value("Lease Contract", lease.name, "status", "Expiring")
	elif state == "Renewed":
		frappe.db.set_value("Lease Contract", lease.name, "status", "Renewed")
		frappe.db.set_value("Unit", unit, {"status": "Vacant", "current_lease": None})
		_settle_old_deposit(lease, spec)
	elif state == "Expired":
		frappe.db.set_value("Lease Contract", lease.name, "status", "Expired")
		frappe.db.set_value("Unit", unit, {"status": "Vacant", "current_lease": None})
		_settle_old_deposit(lease, spec)
	elif state == "Terminated":
		doc = frappe.get_doc("Lease Contract", lease.name)
		termination = T(spec.get("terminate", -10))
		outstanding = doc.get_outstanding_rent(upto_date=termination)
		doc.terminate(termination_date=termination, reason="Tenant gave notice and vacated.",
		              reasons="Tenancy Surrendered", outstanding_rent=outstanding)
		_settle_old_deposit(doc, spec)


def _settle_old_deposit(lease, spec):
	"""Refund (or part-refund) the deposit of a lease that has ended. The status and amounts are set through the
	app's own Security Deposit.refund(); the ledger entries are posted here because the app's refund journal
	(core.security_deposit_accounting.process_refund_or_forfeit) pays the customer from the bank account in a way
	ERPNext v16 rejects."""
	key = spec["key"]
	if key not in D.DEPOSIT_SETTLEMENTS or not lease.security_deposit:
		return
	deduction, reason = D.DEPOSIT_SETTLEMENTS[key]
	dep = frappe.get_doc("Security Deposit", lease.security_deposit)
	if dep.docstatus != 1 or dep.status != "Held":
		return
	dep.refund(deduction_amount=deduction, deduction_reason=reason)
	customer = _customer_of(dep.tenant)
	liability = acct("Tenant Security Deposits Payable")
	refund = flt(dep.amount) - flt(deduction)

	def journal(remark, credit_account, amount):
		je = frappe.new_doc("Journal Entry")
		je.company = COMPANY
		je.posting_date = nowdate()
		je.user_remark = remark
		je.append("accounts", {"account": liability, "debit_in_account_currency": amount,
		                       "party_type": "Customer", "party": customer})
		je.append("accounts", {"account": credit_account, "credit_in_account_currency": amount})
		je.insert(ignore_permissions=True)
		je.submit()
		tag("Journal Entry", je.name)

	if flt(deduction) > 0:
		journal(f"Security deposit deduction - {dep.name}", acct("Forfeited Security Deposits"), deduction)
	if refund > 0:
		journal(f"Security deposit refund - {dep.name}", acct("Gulf Mercantile Bank"), refund)


