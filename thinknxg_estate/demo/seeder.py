def _force_delete(doctype, name):
	"""Delete a document, cancelling accounting entries properly (so the ledger is reversed) and simply marking
	the app's own submitted records cancelled first, since their links to each other forbid a normal cancel."""
	try:
		if doctype == "Unit":
			frappe.db.set_value("Unit", name, {"status": "Vacant", "current_lease": None}, update_modified=False)
		doc = frappe.get_doc(doctype, name)
		if doc.docstatus == 1:
			if doctype in ACCOUNTING:
				doc.flags.ignore_permissions = True
				doc.flags.ignore_links = True
				doc.cancel()
			else:
				frappe.db.set_value(doctype, name, "docstatus", 2, update_modified=False)
		frappe.delete_doc(doctype, name, force=1, ignore_permissions=True, delete_permanently=True)
		frappe.db.commit()
		return True
	except Exception as e:
		frappe.db.rollback()
		if doctype in ACCOUNTING:
			# a party or account that is already gone: drop the voucher and its ledger rows directly
			try:
				frappe.db.set_value(doctype, name, "docstatus", 2, update_modified=False)
				for ledger in ("GL Entry", "Payment Ledger Entry"):
					frappe.db.delete(ledger, {"voucher_no": name})
				frappe.delete_doc(doctype, name, force=1, ignore_permissions=True, delete_permanently=True)
				frappe.db.commit()
				return True
			except Exception as e2:
				frappe.db.rollback()
				e = e2
		warn(f"reset {doctype} {name}", e)
		return False


def _tagged(doctype):
	return frappe.get_all("Tag Link", filters={"document_type": doctype, "tag": TAG}, pluck="document_name")


def reset_data(drop_company=0):
	"""Remove everything the seeder created (accounting documents of the demo company, then the app's records),
	restore the CRM settings it changed, and forget the registry."""
	frappe.set_user("Administrator")
	frappe.flags.mute_emails = True
	frappe.flags.estate_bulk_load = True
	import frappe.utils.background_jobs as bg
	frappe.enqueue = bg.enqueue = lambda *a, **k: None
	log("Resetting demo data ...")
	if frappe.db.exists("Company", COMPANY):
		# stop invoices being re-created by link validation: detach first
		frappe.db.sql("update `tabRent Installment` set sales_invoice=NULL, pdc=NULL where parent in "
		              "(select name from `tabRent Schedule` where company=%s)", COMPANY)
		for dt in ACCOUNTING:
			names = set(frappe.get_all(dt, filters={"company": COMPANY}, pluck="name", order_by="creation desc"))
			if dt == "Purchase Invoice":
				suppliers = _tagged("Supplier")
				if suppliers:
					names |= set(frappe.get_all(dt, filters={"supplier": ["in", suppliers]}, pluck="name"))
			for name in sorted(names, reverse=True):
				_force_delete(dt, name)
		frappe.db.commit()
	deleted = {}
	for dt in RESET_ORDER:
		names = set(_tagged(dt))
		if dt in ("Lease Contract", "Rent Schedule", "Security Deposit", "Post Dated Cheque", "Expense Property",
		          "Property", "Unit", "Maintenance Job", "Reservation", "Commission Entry", "Listing"):
			meta = frappe.get_meta(dt)
			if meta.has_field("company"):
				names |= set(frappe.get_all(dt, filters={"company": COMPANY}, pluck="name"))
		for name in names:
			if frappe.db.exists(dt, name) and _force_delete(dt, name):
				deleted[dt] = deleted.get(dt, 0) + 1
		frappe.db.commit()
	for user in set(_tagged("User")):
		if user not in ("Administrator", "Guest") and frappe.db.exists("User", user):
			if not _force_delete("User", user):
				frappe.db.set_value("User", user, "enabled", 0)
	backup = frappe.db.get_default("estate_demo_crm_settings_backup")
	if backup:
		for field, value in json.loads(backup).items():
			frappe.db.set_single_value("RE CRM Settings", field, value)
		frappe.db.set_default("estate_demo_crm_settings_backup", "")
	for name in frappe.get_all("Tag Link", filters={"tag": TAG}, pluck="name"):
		frappe.db.delete("Tag Link", {"name": name})
	if frappe.db.exists("Tag", TAG):
		frappe.delete_doc("Tag", TAG, force=1, ignore_permissions=True)
	global REG
	reg().clear()
	REG = None
	if int(drop_company) and frappe.db.exists("Company", COMPANY):
		frappe.delete_doc("Company", COMPANY, force=1, ignore_permissions=True)
	frappe.db.commit()
	log("Reset complete: " + (", ".join(f"{k} {v}" for k, v in deleted.items()) or "nothing to remove"))
	return deleted


def reset(drop_company=0):
	return reset_data(drop_company)


