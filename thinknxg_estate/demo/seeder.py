def ensure_foundation():
	log("[1/12] Company, chart of accounts, fiscal years, tax templates")
	c = D.COMPANY
	if not frappe.db.exists("Currency", "AED") or not frappe.db.get_value("Currency", "AED", "enabled"):
		if frappe.db.exists("Currency", "AED"):
			frappe.db.set_value("Currency", "AED", "enabled", 1)
		else:
			frappe.get_doc({"doctype": "Currency", "currency_name": "AED", "symbol": "AED",
			                "fraction": "Fils", "number_format": "#,###.##", "enabled": 1}).insert()

	if not frappe.db.exists("Company", c["name"]):
		frappe.get_doc({
			"doctype": "Company", "company_name": c["name"], "abbr": c["abbr"], "default_currency": "AED",
			"country": "United Arab Emirates", "tax_id": c["tax_id"],
			"create_chart_of_accounts_based_on": "Standard Template", "chart_of_accounts": "Standard",
		}).insert(ignore_permissions=True)
	tag("Company", c["name"])
	frappe.defaults.set_user_default("Company", c["name"])

	for year in (2024, 2025, 2026, 2027):
		fy = str(year)
		if not frappe.db.exists("Fiscal Year", fy):
			frappe.get_doc({"doctype": "Fiscal Year", "year": fy, "year_start_date": f"{year}-01-01",
			                "year_end_date": f"{year}-12-31"}).insert(ignore_permissions=True)

	def make_account(name, parent, account_type=None, root_type=None):
		full = acct(name)
		if frappe.db.exists("Account", full):
			return full
		parent_full = acct(parent)
		if not frappe.db.exists("Account", parent_full):
			raise RuntimeError(f"Parent account {parent_full} not found in the chart")
		doc = frappe.get_doc({"doctype": "Account", "account_name": name, "parent_account": parent_full,
		                      "company": COMPANY, "account_type": account_type or "", "is_group": 0})
		if root_type:
			doc.root_type = root_type
		doc.insert(ignore_permissions=True)
		return doc.name

	make_account("Gulf Mercantile Bank", "Bank Accounts", "Bank")
	make_account("Desert Rose Bank", "Bank Accounts", "Bank")
	make_account("Tenant Security Deposits Payable", "Current Liabilities", "Receivable")
	# the app's deposit journal puts the tenant (a Customer) on this account, which ERPNext only allows on a
	# Receivable-type account
	frappe.db.set_value("Account", acct("Tenant Security Deposits Payable"), "account_type", "Receivable")
	make_account("Forfeited Security Deposits", "Indirect Income")
	make_account("VAT 5%", "Duties and Taxes", "Tax")

	bank = acct("Gulf Mercantile Bank")
	cash = acct("Cash")
	for mop in frappe.get_all("Mode of Payment", pluck="name"):
		doc = frappe.get_doc("Mode of Payment", mop)
		if any(r.company == COMPANY for r in doc.accounts):
			continue
		doc.append("accounts", {"company": COMPANY, "default_account": cash if mop == "Cash" else bank})
		doc.save(ignore_permissions=True)

	# UAE VAT: residential rent is exempt, commercial is 5%.
	vat = acct("VAT 5%")
	for tname, rate in (("UAE Residential Rent (Exempt)", 0), ("UAE Commercial Rent (5% VAT)", 5)):
		full = f"{tname} - {ABBR}"
		if not frappe.db.exists("Item Tax Template", full):
			frappe.get_doc({"doctype": "Item Tax Template", "title": tname, "company": COMPANY,
			                "taxes": [{"tax_type": vat, "tax_rate": rate}]}).insert(ignore_permissions=True)
	if not frappe.db.exists("Sales Taxes and Charges Template", f"UAE VAT 5% - {ABBR}"):
		frappe.get_doc({"doctype": "Sales Taxes and Charges Template", "title": "UAE VAT 5%", "company": COMPANY,
		                "is_default": 1, "taxes": [{"charge_type": "On Net Total", "account_head": vat,
		                                            "description": "VAT 5%", "rate": 5}]}).insert(ignore_permissions=True)

	ps = frappe.get_single("Property Settings")
	if not ps.rent_item:
		try:
			from thinknxg_estate.core.install import ensure_rent_item
			ensure_rent_item()
		except Exception as e:
			warn("rent item", e)
	frappe.db.commit()


def tax_template(commercial):
	return f"UAE Commercial Rent (5% VAT) - {ABBR}" if commercial else f"UAE Residential Rent (Exempt) - {ABBR}"


