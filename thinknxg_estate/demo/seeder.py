def ensure_user(email, first, roles, last=None, user_type="System User"):
	if frappe.db.exists("User", email):
		user = frappe.get_doc("User", email)
	else:
		user = frappe.get_doc({"doctype": "User", "email": email, "first_name": first, "last_name": last or "",
		                       "user_type": user_type, "send_welcome_email": 0, "enabled": 1})
		user.insert(ignore_permissions=True)
		tag("User", email)
	have = {r.role for r in user.roles}
	for role in roles:
		if role not in have and frappe.db.exists("Role", role):
			user.append("roles", {"role": role})
	user.save(ignore_permissions=True)
	from frappe.utils.password import update_password
	update_password(email, demo_password())
	return email


def seed_users_and_agents():
	log("[2/12] Staff, sales agents and brokers")
	r = reg()
	for s in D.STAFF:
		ensure_user(f"{s['email']}@{D.EMAIL_DOMAIN}", s["name"].split()[0], s["roles"], last=s["name"].split()[-1])
	for a in D.AGENTS:
		email = f"{a['email']}@{D.EMAIL_DOMAIN}"
