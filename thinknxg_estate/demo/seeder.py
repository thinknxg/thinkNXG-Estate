def _property_media(p, pname):
	doc = frappe.get_doc("Property", pname)
	if doc.cover_image and len(doc.photos) >= 3:
		return
	title, sub = p["name"], f"{p['area']}, Dubai"
	seed_n = sum(ord(c) for c in p["key"])
	cover = assets.exterior(seed_n, title, sub, p["palette"], p["towers"], p.get("low_rise", False))
	doc.cover_image = attach("Property", pname, f"{p['key']}-cover.png", cover)
	rows = [("Exterior", cover, 1)]
	rows.append(("Living area", assets.interior(seed_n + 1, title, "Living area"), 0))
	rows.append(("Master bedroom", assets.interior(seed_n + 2, title, "Master bedroom", wall=(228, 222, 235)), 0))
	kinds = ["pool", "gym", "garden"]
	for i, kind in enumerate(kinds[:2]):
		rows.append((kind.title(), assets.amenity(seed_n + 10 + i, title, kind.title(), kind), 0))
	doc.photos = []
	for i, (caption, content, is_cover) in enumerate(rows):
		url = attach("Property", pname, f"{p['key']}-{i}.png", content)
		doc.append("photos", {"image": url, "caption": caption, "is_cover": is_cover})
	doc.save(ignore_permissions=True)


def _seed_unit(p, pname, u):
	r = reg()
	no, utype, beds, baths, sqm, furn, parking, rent, extra = u
	ukey = f"unit:{no}"
	uname = r.get(ukey)
	if uname and frappe.db.exists("Unit", uname):
		return uname
	uname = frappe.db.exists("Unit", {"property": pname, "unit_no": no})
	if not uname:
		floor_choice = extra.get("floor")
		doc = frappe.get_doc({
			"doctype": "Unit", "property": pname, "unit_no": no, "unit_type": utype, "company": COMPANY,
			"usage": extra.get("usage", p["usage"]), "area_sqm": sqm, "bedrooms": beds, "bathrooms": baths,
			"furnishing": furn, "parking_slots": parking, "floor": floor_choice,
			"charges": _charges(u, p),
		})
		doc.insert(ignore_permissions=True)
		uname = doc.name
		tag("Unit", uname)
	r.set(ukey, uname)
	return uname


