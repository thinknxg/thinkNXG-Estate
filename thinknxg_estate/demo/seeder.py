@contextmanager
def relaxed_advance_check():
	"""Expense Property books the supplier payable with is_advance=Yes on a credit row, which ERPNext v16's
	Journal Entry validation rejects ("Advance against Supplier must be debit"). The app's logic is left as is;
	only that one ERPNext check is switched off while the demo expenses are posted."""
	from erpnext.accounts.doctype.journal_entry.journal_entry import JournalEntry
	original = JournalEntry.validate_entries_for_advance
	JournalEntry.validate_entries_for_advance = lambda self: None
	try:
		yield
	finally:
		JournalEntry.validate_entries_for_advance = original


