	r = reg()
	names = frappe.get_all("Commission Entry", filters={"company": COMPANY}, fields=["name", "creation", "docstatus", "status"],
	                       order_by="creation asc")
	for n, row in enumerate(names):
		tag("Commission Entry", row.name)
		doc = frappe.get_doc("Commission Entry", row.name)
		if row.docstatus == 0 and n < len(names) - 1:
			doc.submit()
			doc.reload()
			if n < 2:
				doc.mark_paid()
	frappe.db.commit()


