def _seed_deal(lead, L, agent, unit):
	r = reg()
	deal_name = lead.make_deal()
	deal = frappe.get_doc("RE Deal", deal_name)
	tag("RE Deal", deal_name)
	stage = L["stage"]
	deal.pipeline_stage = stage if stage not in ("Won", "Reservation", "Lost") else "Negotiation"
	deal.probability = {"New": 15, "Contacted": 25, "Site Visit Scheduled": 40, "Negotiation": 60,
	                    "Reservation": 80, "Won": 100, "Lost": 0}[stage]
	deal.expected_close = T(14 if stage in ("Negotiation", "Reservation") else 30) if stage != "Won" else T(-5)
	deal.notes = "Demo deal."
	deal.save(ignore_permissions=True)
	if stage == "Won":
		lease = r.get(f"lease:{L['lease']}")
		deal.lease_contract = lease
		deal.pipeline_stage = "Won"
		deal.save(ignore_permissions=True)
	elif stage == "Lost":
		deal.lost_reason = L["lost"]
		deal.pipeline_stage = "Lost"
		deal.save(ignore_permissions=True)
	elif stage == "Reservation":
		_ensure_customer(L["name"])
		res = frappe.get_doc({"doctype": "Reservation", "deal": deal_name, "unit": unit,
		                      "booking_fee": L["fee"], "valid_till": T(7 if L["name"].startswith("Ingrid") else 3)})
		res.insert(ignore_permissions=True)
		res.submit()
		tag("Reservation", res.name)
		deal.reload()
		deal.reservation = res.name
		deal.pipeline_stage = "Reservation"
		deal.save(ignore_permissions=True)
	backdate("RE Deal", deal_name, L["ago"], hour=11)
	frappe.db.set_value("RE Lead", lead.name, "status", L["status"])


def _seed_visits():
	r = reg()
	for i, (name, offset, hour, outcome, feedback) in enumerate(D.VISITS):
		key = f"visit:{i}"
